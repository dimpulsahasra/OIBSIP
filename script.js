// ========================================
// SUBMIT QUIZ
// ========================================

function submitQuiz() {

    playerAnswers = {};

    let score = 0;

    for (const question of selectedQuestions) {

        const selected =
            document.querySelector(
                `input[name="player-${question.id}"]:checked`
            );

        if (!selected) {

            alert(
                `Please answer Question ${question.id} ❤️`
            );

            return;
        }

        const answer =
            Number(selected.value);

        playerAnswers[question.id] =
            answer;

        if (
            answer ===
            Number(
                creatorAnswers[question.id]
            )
        ) {

            score++;
        }
    }

    const total =
        selectedQuestions.length;

    const percentage =
        Math.round(
            (score / total) * 100
        );

    displayResult(
        score,
        total,
        percentage
    );
}


// ========================================
// RESULT
// ========================================

function displayResult(
    score,
    total,
    percentage
) {

    showSection("result");

    const scoreElement =
        document.getElementById("score");

    const percentageElement =
        document.getElementById("percentage");

    const messageElement =
        document.getElementById(
            "resultMessage"
        );

    if (scoreElement) {
        scoreElement.innerText =
            `${score} / ${total}`;
    }

    if (percentageElement) {
        percentageElement.innerText =
            `${percentage}%`;
    }

    let message = "";

    if (percentage >= 90) {

        message =
            "OMG! You know them PERFECTLY! 💕🥹";

    } else if (percentage >= 70) {

        message =
            "Wow! You know them really well! ❤️";

    } else if (percentage >= 50) {

        message =
            "Not bad! You still have some learning to do 😜";

    } else {

        message =
            "Oops! You need to know them better 😂💔";
    }

    if (messageElement) {
        messageElement.innerText =
            message;
    }


    const results =
        document.getElementById("results");

    if (!results) return;

    results.innerHTML = "";


    selectedQuestions.forEach(
        (question, index) => {

            const correct =
                Number(
                    creatorAnswers[
                        question.id
                    ]
                );

            const given =
                Number(
                    playerAnswers[
                        question.id
                    ]
                );

            const correctOption =
                question.options[correct];

            const givenOption =
                question.options[given];

            const isCorrect =
                correct === given;

            const resultCard =
                document.createElement("div");

            resultCard.className =
                "answer-result";

            resultCard.innerHTML = `

                <h3>
                    ${index + 1}.
                    ${question.q}
                </h3>

                <div class="answer-row">

                    <img
                        src="${emojiToImage(
                            givenOption[1]
                        )}"
                        onerror="
                            this.style.display='none';
                            this.nextElementSibling.style.display='inline';
                        "
                    >

                    <span>
                        Your answer:
                        <b>${givenOption[0]}</b>
                    </span>

                </div>

                <div class="answer-row">

                    <img
                        src="${emojiToImage(
                            correctOption[1]
                        )}"
                        onerror="
                            this.style.display='none';
                            this.nextElementSibling.style.display='inline';
                        "
                    >

                    <span>
                        Correct answer:
                        <b>${correctOption[0]}</b>
                    </span>

                </div>

                <div class="${
                    isCorrect
                        ? "correct"
                        : "wrong"
                }">

                    ${
                        isCorrect
                            ? "✅ Correct!"
                            : "❌ Wrong!"
                    }

                </div>
            `;

            results.appendChild(
                resultCard
            );
        }
    );
}


